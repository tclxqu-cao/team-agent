#!/usr/bin/env node
import { execFileSync } from "node:child_process";
import { readFile, writeFile, mkdir, lstat, readlink } from "node:fs/promises";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";
import {
  RELEASE_PACKAGE_DIRECTORIES as directories, RELEASE_PACKAGE_NAMES as names,
  compareAgentRoamVersions, createNpmClient, redactReleaseError,
} from "./agentroam-release-lib.mjs";

const root = resolve(fileURLToPath(new URL("..", import.meta.url)));
const exactVersion = /^\d+\.\d+\.\d+(?:-preview\.\d+)?$/;
const shared = ["package.json", "bun.lock", "package-lock.json", "tsconfig.json", "config/", "patches/"];

// Include source imported from Desktop by Server/WebApp and TUI. Unknown build
// helpers conservatively invalidate bundles; generated output is git-ignored.
export function affectedPackages(path) {
  if (/(?:^|\/)(?:node_modules|dist|release|\.next|\.build-remote)(?:\/|$)/.test(path)
    || /\.(?:tgz|app)(?:\/|$)/.test(path)
    || /^packages\/(?:runtime-[^/]+\/runtime|cloudflared-[^/]+\/vendor)(?:\/|$)/.test(path)) return [];
  if (path.startsWith("packages/server/native/remote-helper/") || path === "packages/desktop/native/desktop-input.swift") return [names[0]];
  // Publication orchestration and audits do not enter npm runtime contents.
  if (["scripts/incremental-cli-release.mjs", "scripts/agentroam-release-lib.mjs", "scripts/publish-agentroam-release.mjs", "scripts/agent-runtime-upgrade-lib.mjs", "scripts/collect-cli-artifacts.mjs"].includes(path)
    || /^scripts\/audit-/.test(path)) return [];
  const own = directories.findIndex((directory) => path.startsWith(`${directory}/`));
  if (own >= 0) return [names[own]];
  if (shared.some((prefix) => path === prefix || (prefix.endsWith("/") && path.startsWith(prefix)))) return names.slice();
  if (path.startsWith("packages/tui/")) return names.slice(4, 6);
  if (["packages/core/", "packages/desktop/", "packages/sdk/"].some((prefix) => path.startsWith(prefix))) return [names[0], names[1], names[4], names[5]];
  if (["packages/server/", "packages/webapp/"].some((prefix) => path.startsWith(prefix))) return names.slice(0, 2);
  if (path === "scripts/build-cli-remote-helper.mjs") return [names[0]];
  if (path === "scripts/build-tui-package.mjs") return names.slice(4, 6);
  if (path === "scripts/fetch-cloudflared-package.mjs") return names.slice(2, 4);
  if (path.startsWith("scripts/") && !/\.(?:test|spec)\./.test(path)) return names.slice();
  return [];
}

export function normalizeReleaseInput(path, content) {
  if (content === null) return null;
  if (path === "package.json" || path.endsWith("/package.json") || path.endsWith("/manifest.json")) {
    const value = JSON.parse(content);
    if (path === "package.json" && value.scripts) {
      delete value.scripts["plan:cli"];
      delete value.scripts["pack:cli"];
    }
    // Platform version bumps and launcher pins are generated by this planner.
    if (directories.some((directory) => path.startsWith(`${directory}/`))) {
      delete value.version;
      delete value.packageVersion;
      for (const name of names) if (value.optionalDependencies?.[name]) value.optionalDependencies[name] = "<release>";
    }
    return JSON.stringify(value);
  }
  if (["packages/cli/src/platform-packages.ts", "packages/cli/bin/node-preflight.mjs", "packages/cli/install/install-agentroam.sh", "packages/cli/install/install-agentroam.ps1", "packages/cli/src/tunnel/public-readiness.ts"].includes(path)) return content.replace(/\b\d+\.\d+\.\d+-preview\.\d+\b/g, "<release>");
  return content;
}

export function planRelease({ base, version, baselinePackages, changes }) {
  if (!exactVersion.test(version)) throw new Error("--version requires X.Y.Z or X.Y.Z-preview.N");
  const baselineCli = baselinePackages.at(-1);
  if (compareAgentRoamVersions(version, baselineCli.version) <= 0) throw new Error("new release must be newer than baseline launcher");
  const reasons = new Map(names.map((name) => [name, []]));
  for (const { path, before, after } of changes) {
    if (normalizeReleaseInput(path, before) === normalizeReleaseInput(path, after)) continue;
    for (const name of affectedPackages(path)) reasons.get(name).push(path);
  }
  if (names.slice(0, -1).some((name) => reasons.get(name).length)) reasons.get("agentroam").push("platform dependency versions changed");
  const packages = names.map((name, index) => {
    const old = baselinePackages[index];
    if (old.name !== name || !exactVersion.test(old.version)) throw new Error(`invalid baseline package ${name}`);
    if (index < names.length - 1 && baselineCli.optionalDependencies?.[name] !== old.version) throw new Error(`baseline launcher dependency mismatch: ${name}`);
    const changed = reasons.get(name).length > 0;
    if (changed && compareAgentRoamVersions(version, old.version) <= 0) throw new Error(`new version must exceed ${name}@${old.version}`);
    return { name, directory: directories[index], version: changed ? version : old.version, previousVersion: old.version, changed, reasons: reasons.get(name) };
  });
  return { schemaVersion: 1, base, version, noop: !packages.some((item) => item.changed), packages };
}

export async function readReleasePlan(cwd, base, version) {
  const git = (args, encoding = "utf8") => execFileSync("git", args, { cwd, encoding, stdio: ["ignore", "pipe", "pipe"], maxBuffer: 32 * 1024 * 1024 });
  const sourceText = (bytes) => {
    try { return new TextDecoder("utf-8", { fatal: true }).decode(bytes); }
    catch { return `binary:${bytes.toString("base64")}`; }
  };
  // Resolve first to reject option-like refs and use immutable object IDs below.
  const commit = git(["rev-parse", "--verify", "--end-of-options", `${base}^{commit}`]).trim();
  const baselinePackages = directories.map((directory) => JSON.parse(git(["show", `${commit}:${directory}/package.json`])));
  const paths = new Set([
    ...git(["diff", "--name-only", "--no-renames", "-z", commit, "--"]).split("\0"),
    ...git(["ls-files", "--others", "--exclude-standard", "-z"]).split("\0"),
  ].filter((path) => path && affectedPackages(path).length));
  const changes = [];
  for (const path of paths) {
    let before = null;
    let after = null;
    try { before = sourceText(git(["show", `${commit}:${path}`], "buffer")); } catch (error) { if (error.status !== 128) throw error; }
    try {
      const file = resolve(cwd, path);
      const info = await lstat(file);
      if (info.isDirectory()) throw new Error(`source directory or submodule needs explicit release handling: ${path}`);
      after = info.isSymbolicLink() ? await readlink(file) : sourceText(await readFile(file));
    } catch (error) { if (error.code !== "ENOENT") throw error; }
    changes.push({ path, before, after });
  }
  return planRelease({ base: commit, version, baselinePackages, changes });
}

export function buildCommands(plan) {
  const commands = [];
  const changed = new Set(plan.packages.filter((item) => item.changed).map((item) => item.name));
  const runtime = names.slice(0, 2).some((name) => changed.has(name));
  const tui = names.slice(4, 6).some((name) => changed.has(name));
  if (runtime) commands.push(["bun", ["run", "--cwd", "packages/webapp", "build"]], ["bun", ["run", "--cwd", "packages/core", "build"]], ["bun", ["run", "--cwd", "packages/server", "build"], { NEXT_STANDALONE: "1" }]);
  if (tui) {
    const targets = names.slice(4, 6).filter((name) => changed.has(name)).map((name) => name.endsWith("darwin-arm64") ? "darwin-arm64" : "windows-amd64");
    commands.push(["bun", ["scripts/build-tui-package.mjs", "--targets", targets.join(",")]]);
  }
  if (changed.has("agentroam")) commands.push(["bun", ["run", "--cwd", "packages/cli", "build"]]);
  for (const item of plan.packages.filter((item) => item.changed)) {
    const kind = item.name === "agentroam" ? "cli" : item.name.includes("runtime-") ? "runtime" : item.name.includes("cloudflared-") ? "cloudflared" : "tui";
    if (kind === "runtime") commands.push([process.execPath, ["scripts/stage-cli-runtime.mjs", "--target", item.name.endsWith("darwin-arm64") ? "darwin-arm64" : "windows-amd64"]]);
    if (kind === "cloudflared") commands.push([process.execPath, ["scripts/fetch-cloudflared-package.mjs", item.directory]]);
    commands.push([process.execPath, ["scripts/pack-package.mjs", item.directory, `scripts/audit-${kind}-tarball.mjs`]]);
  }
  return commands;
}

export async function prepareRelease(cwd, plan, npmClient) {
  // Download every reused package before editing manifests. Missing/staged npm
  // versions must never be silently substituted or republished.
  const reused = new Map();
  for (const item of plan.packages.filter((item) => !item.changed)) {
    if (!await npmClient.getVersion(item.name, item.version)) throw new Error(`reused package is unavailable: ${item.name}@${item.version}`);
    const bytes = await npmClient.download(item.name, item.version);
    reused.set(item.name, bytes);
  }
  for (const item of plan.packages.filter((item) => item.changed)) {
    if (await npmClient.getVersion(item.name, item.version)) throw new Error(`new version already exists: ${item.name}@${item.version}`);
  }
  for (const item of plan.packages) {
    const file = resolve(cwd, item.directory, "package.json");
    const value = JSON.parse(await readFile(file, "utf8"));
    value.version = item.version;
    if (item.name === "agentroam") {
      value.optionalDependencies = { ...value.optionalDependencies, ...Object.fromEntries(plan.packages.slice(0, -1).map((dependency) => [dependency.name, dependency.version])) };
    }
    await writeFile(file, `${JSON.stringify(value, null, 2)}\n`);
    if (item.name.includes("runtime-") || item.name.includes("cloudflared-")) {
      const manifestPath = resolve(cwd, item.directory, "manifest.json");
      const manifest = JSON.parse(await readFile(manifestPath, "utf8"));
      manifest.packageVersion = item.version;
      await writeFile(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`);
    }
    if (reused.has(item.name)) {
      const filename = `${item.name.replace(/^@/, "").replaceAll("/", "-")}-${item.version}.tgz`;
      await writeFile(resolve(cwd, item.directory, filename), reused.get(item.name));
    }
  }
  // Existing generated release text remains compatible with the full-release
  // upgrade workflow; don't rewrite agent engine versions or arbitrary source.
  for (const path of ["packages/cli/src/platform-packages.ts", "packages/cli/bin/node-preflight.mjs", "packages/cli/install/install-agentroam.sh", "packages/cli/install/install-agentroam.ps1", "packages/cli/src/tunnel/public-readiness.ts"]) {
    const file = resolve(cwd, path);
    const content = await readFile(file, "utf8");
    await writeFile(file, content.replace(/\b\d+\.\d+\.\d+-preview\.\d+\b/g, plan.version));
  }
}

export async function main(args = process.argv.slice(2)) {
  const option = (name) => args[args.indexOf(name) + 1];
  if (!args.includes("--base") || !args.includes("--version")) throw new Error("usage: incremental-cli-release.mjs --base <published-git-ref> --version <new-version> [--pack]");
  const plan = await readReleasePlan(root, option("--base"), option("--version"));
  console.log(JSON.stringify(plan, null, 2));
  if (!args.includes("--pack") || plan.noop) return plan;
  await prepareRelease(root, plan, createNpmClient());
  for (const [command, commandArgs, env] of buildCommands(plan)) {
    execFileSync(command, commandArgs, { cwd: root, stdio: "inherit", env: { ...process.env, ...env } });
  }
  execFileSync(process.execPath, ["scripts/collect-cli-artifacts.mjs"], { cwd: root, stdio: "inherit" });
  await mkdir(resolve(root, "dist/cli-release"), { recursive: true });
  await writeFile(resolve(root, "dist/cli-release/incremental-plan.json"), `${JSON.stringify(plan, null, 2)}\n`);
  return plan;
}

if (resolve(process.argv[1] ?? "") === fileURLToPath(import.meta.url)) main().catch((error) => {
  console.error(redactReleaseError(error.message));
  process.exitCode = 1;
});
