export const DEFAULT_THEME_ID: WebThemeId = "black";

export const WEB_THEME_MAP = Object.fromEntries(WEB_THEMES.map((theme) => [theme.id, theme])) as Record<
  WebThemeId,
  WebTheme
>;

export function resolveWebTheme(id: string | null | undefined): WebTheme {
  const normalized = id === "dark" ? DEFAULT_THEME_ID : id;
  if (normalized && normalized in WEB_THEME_MAP) return WEB_THEME_MAP[normalized as WebThemeId];
  return WEB_THEME_MAP[DEFAULT_THEME_ID];
}
